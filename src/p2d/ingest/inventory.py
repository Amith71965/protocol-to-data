"""Building the data inventory document.

Produces ``docs/data_inventory.md`` (narrative, committed) and
``reports/data_profile.csv`` (per-variable detail, regenerated).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path

import pandas as pd

from p2d.ingest.profile import DatasetProfile, profile_frame, profiles_to_frame
from p2d.ingest.reader import read_domain
from p2d.sources import (
    ABSENT_DOMAINS,
    PHUSE_LICENSE,
    PHUSE_LICENSE_URL,
    PROTOCOL_ID,
    SDTM_DOMAINS,
    STUDY_ID,
)

#: Lab analytes the protocol's exclusion criteria name but the study does not
#: publish. Recorded here so the coverage report can cite a concrete reason.
MISSING_LAB_TESTS = {
    "folate": "EXCL28 names folate; no folate test is present in LB.",
    "total T4": "EXCL28 names total T4; not present in LB.",
    "thyroid uptake": "EXCL28 names thyroid uptake; not present in LB.",
    "free thyroid index": "EXCL28 names the free thyroid index; not present in LB.",
    "syphilis": "EXCL29 requires syphilis screening; no such test is present in LB.",
}


@dataclass(frozen=True)
class InventorySummary:
    n_domains: int
    total_rows: int
    profiles: list[DatasetProfile]


def build_profiles(raw_dir: str | Path) -> list[DatasetProfile]:
    """Profile every published domain found under ``raw_dir``."""
    profiles = []
    for domain in sorted(SDTM_DOMAINS):
        path = Path(raw_dir) / "sdtm" / f"{domain}.xpt"
        if not path.exists():
            continue
        profiles.append(profile_frame(read_domain(raw_dir, domain), domain.upper()))
    return profiles


def _arm_breakdown(raw_dir: str | Path) -> pd.Series | None:
    path = Path(raw_dir) / "sdtm" / "dm.xpt"
    if not path.exists():
        return None
    dm = read_domain(raw_dir, "dm")
    return dm["ARM"].value_counts().sort_index()


def render_markdown(profiles: list[DatasetProfile], arms: pd.Series | None) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Data inventory")
    add("")
    add(
        f"Study `{STUDY_ID}` (sponsor protocol `{PROTOCOL_ID}`), profiled {date.today().isoformat()}."
    )
    add("")
    add(
        f"All datasets are downloaded from the {PHUSE_LICENSE}-licensed PHUSE repository "
        f"(<{PHUSE_LICENSE_URL}>). Nothing is committed; `docs/data_manifest.json` pins the "
        "checksums the reports were produced from."
    )
    add("")
    add("This document is generated by `scripts/profile_data.py`.")
    add("")

    add("## Published domains")
    add("")
    add("| Domain | Rows | Subjects | Variables |")
    add("|---|---:|---:|---:|")
    for profile in profiles:
        subjects = f"{profile.subjects:,}" if profile.subjects else "—"
        add(f"| {profile.domain} | {profile.rows:,} | {subjects} | {profile.n_columns} |")
    add("")
    add("Per-variable detail, including null rates and distinct counts, is in")
    add("`reports/data_profile.csv`.")
    add("")

    if arms is not None:
        total = int(arms.sum())
        randomized = int(arms.drop(labels=["Screen Failure"], errors="ignore").sum())
        add("## Population")
        add("")
        add("| Arm | Subjects |")
        add("|---|---:|")
        for arm, count in arms.items():
            add(f"| {arm} | {count} |")
        add(f"| **Total** | **{total}** |")
        add("")
        add(
            f"{total} subjects are in DM, of whom **{randomized} were randomized** and "
            f"{total - randomized} were screen failures. The screen failures have no "
            "questionnaire, laboratory or medical-history records at all."
        )
        add("")
        add(
            "This drives every eligibility rule: a criterion is evaluated against the "
            "randomized population, because a screen failure was *correctly* excluded and "
            "flagging one would be a false positive. Subjects with no data for a criterion "
            "are reported as **not evaluable** rather than as passing."
        )
        add("")

    add("## What is absent")
    add("")
    add(
        "These gaps are the reason the project reports partial criteria coverage. They are "
        "recorded here so the coverage report can cite a concrete cause rather than a "
        "silent omission."
    )
    add("")
    add("| Missing | Consequence |")
    add("|---|---|")
    for domain, reason in sorted(ABSENT_DOMAINS.items()):
        add(f"| `{domain}` domain | {reason} |")
    for test, reason in sorted(MISSING_LAB_TESTS.items()):
        add(f"| {test} (lab test) | {reason} |")
    add("")

    add("## Reading notes")
    add("")
    add(
        "**Denormal zeros.** The XPORT files decode a stored zero as `5.397605e-79` rather "
        "than `0.0`. Sums are unaffected, but comparisons and null tests are not: a "
        "questionnaire item scored zero would otherwise compare as greater than zero. "
        "`p2d.ingest.reader` snaps these to exact zero on read, and a regression test "
        "guards it."
    )
    add("")
    add(
        "**Character padding.** Character columns arrive space-padded to fixed width, which "
        "breaks equality against controlled terminology. They are stripped on read."
    )
    add("")

    return "\n".join(lines) + "\n"


def write_inventory(
    raw_dir: str | Path,
    markdown_path: str | Path,
    csv_path: str | Path,
) -> InventorySummary:
    """Profile everything and write both outputs."""
    profiles = build_profiles(raw_dir)

    frame = profiles_to_frame(profiles)
    Path(csv_path).parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(csv_path, index=False)

    markdown = render_markdown(profiles, _arm_breakdown(raw_dir))
    Path(markdown_path).parent.mkdir(parents=True, exist_ok=True)
    Path(markdown_path).write_text(markdown)

    return InventorySummary(
        n_domains=len(profiles),
        total_rows=sum(p.rows for p in profiles),
        profiles=profiles,
    )
