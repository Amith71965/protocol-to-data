"""Generating the mapping specification.

The specification is produced from the domain configurations and from an actual
round-trip run, so the match rate printed beside each variable is measured
rather than claimed. A variable that stops reconciling changes this document
the next time it is generated.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from pathlib import Path

import pandas as pd

from p2d.mapping.findings import FindingsDomain
from p2d.mapping.verify import RoundTripReport

#: How a variable gets its value.
COLLECTED = "collected"
DERIVED = "derived"
CARRIED = "carried"

#: Documented derivation rules, keyed by the variable suffix they apply to.
DERIVATION_NOTES = {
    "STUDYID": "Study-level constant.",
    "DOMAIN": "Domain-level constant.",
    "USUBJID": "Assembled as 01-<site>-<subject>.",
    "SITEID": "The site number collected on the page.",
    "SEQ": "1-based counter within subject, ordered by the domain's sequence sort.",
    "DY": "Study day against DM.RFSTDTC; there is no day zero.",
    "BLFL": "Y on records collected at the domain's nominated baseline visit.",
    "TEST": "Decoded from --TESTCD through the domain's controlled terminology.",
    "STRESN": "Collected result converted to standard units (docs/unit_conversions.csv).",
    "STRESU": "Standard unit from the conversion rule.",
    "STRESC": "Character form of the standardised result.",
    "NRIND": "NORMAL / LOW / HIGH, from the standardised result against its reference range.",
}


@dataclass(frozen=True)
class SpecRow:
    domain: str
    sdtm_variable: str
    source: str
    derivation: str
    match_rate: str
    notes: str


def _derivation_for(variable: str) -> str:
    for suffix, note in DERIVATION_NOTES.items():
        if variable.endswith(suffix):
            return note
    return ""


def build_rows(
    spec: FindingsDomain | None,
    report: RoundTripReport,
    *,
    collected: list[str],
    derived: list[str],
) -> list[SpecRow]:
    """One row per SDTM variable in a domain."""
    rates = {r.variable: r.match_rate for r in report.results}
    not_reproducible = dict(spec.not_reproducible) if spec else {}

    rows = []
    for variable in sorted({*collected, *derived, *not_reproducible}):
        if variable in not_reproducible:
            source, notes = CARRIED, not_reproducible[variable]
            rate = ""
        else:
            source = DERIVED if variable in derived else COLLECTED
            notes = ""
            rate = f"{rates[variable]:.3%}" if variable in rates else ""
        rows.append(
            SpecRow(
                domain=report.domain,
                sdtm_variable=variable,
                source=source,
                derivation=_derivation_for(variable) if source == DERIVED else "",
                match_rate=rate,
                notes=notes,
            )
        )
    return rows


def to_frame(rows: list[SpecRow]) -> pd.DataFrame:
    return pd.DataFrame(
        [
            {
                "domain": r.domain,
                "sdtm_variable": r.sdtm_variable,
                "source": r.source,
                "derivation": r.derivation,
                "roundtrip_match_rate": r.match_rate,
                "notes": r.notes,
            }
            for r in rows
        ]
    )


def render_markdown(frame: pd.DataFrame, reports: list[RoundTripReport]) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Mapping specification")
    add("")
    add(f"Generated by `scripts/build_sdtm.py` on {date.today().isoformat()}.")
    add("")
    add(
        "Each domain is transposed from SDTM to the CRF page it came from, then mapped "
        "back. The match rate beside every variable is measured on that reconstruction "
        "against the published data — it is not a claim."
    )
    add("")
    add("## About the source layer")
    add("")
    add(
        "The pilot study publishes mapped SDTM only; no raw or CRF-shaped data exists "
        "for it anywhere. The CRF layer here is therefore **derived from the published "
        "SDTM**, using `define.xml` origin annotations for page structure. It is a "
        "labelled fixture for exercising and proving the mapping, and is never presented "
        "as trial data."
    )
    add("")
    add("This is why the round trip matters: it is the evidence that the mapping")
    add("specification is complete, in the sense that nothing the CRF layer holds is")
    add("lost or invented on the way back to SDTM.")
    add("")

    add("## Round-trip results")
    add("")
    add("| Domain | Records | Variables | Result |")
    add("|---|---:|---:|---|")
    for report in reports:
        verdict = "exact" if report.exact else f"{len(report.mismatched)} variable(s) below 100%"
        add(f"| {report.domain} | {report.rows_rebuilt:,} | {len(report.results)} | {verdict} |")
    add("")

    imperfect = [r for report in reports for r in report.mismatched]
    if imperfect:
        add("### Variables that do not fully reconcile")
        add("")
        add("| Domain | Variable | Match rate | Mismatches |")
        add("|---|---|---:|---:|")
        for report in reports:
            for r in report.mismatched:
                add(
                    f"| {report.domain} | {r.variable} | {r.match_rate:.3%} | "
                    f"{r.mismatches:,} of {r.total:,} |"
                )
        add("")

    add("## Variable specification")
    add("")
    add("| Domain | SDTM variable | Source | Derivation | Round-trip | Notes |")
    add("|---|---|---|---|---:|---|")
    for row in frame.itertuples():
        add(
            f"| {row.domain} | `{row.sdtm_variable}` | {row.source} | {row.derivation} | "
            f"{row.roundtrip_match_rate} | {row.notes} |"
        )
    add("")
    add("`collected` means the value comes from the CRF page unchanged. `derived` means")
    add("the mapper computes it. `carried` means the published value is passed through")
    add("because a CRF cannot determine it; the reason is given in the notes.")
    add("")
    return "\n".join(lines) + "\n"


def write(frame: pd.DataFrame, reports: list[RoundTripReport], docs_dir: Path) -> None:
    docs_dir.mkdir(parents=True, exist_ok=True)
    frame.to_csv(docs_dir / "mapping_spec.csv", index=False)
    (docs_dir / "mapping_spec.md").write_text(render_markdown(frame, reports))
