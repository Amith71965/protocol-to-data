"""Writing the validation report."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd

from p2d.validate.issues import Issue, to_frame
from p2d.validate.rules import ALL_RULES
from p2d.validate.runner import counts_by_severity, summarise
from p2d.validate.terminology import CODELIST_BINDINGS, UNBOUND_VARIABLES


def render_rules_markdown(issues: list[Issue]) -> str:
    counts = counts_by_severity(issues)
    summary = summarise(issues)

    lines: list[str] = []
    add = lines.append
    add("# Validation rules")
    add("")
    add(f"Generated by `scripts/validate_sdtm.py` on {date.today().isoformat()}.")
    add("")
    add(
        "These are Pinnacle 21 / CDISC CORE style conformance checks, implemented here "
        "so each one is independently tested and each finding traces to a single named "
        'rule rather than to "the validator".'
    )
    add("")

    add("## Results")
    add("")
    add(
        f"**{counts['error']} errors, {counts['warning']} warnings, "
        f"{counts['notice']} notices** across the mapped domains."
    )
    add("")
    if not summary.empty:
        add("| Rule | Severity | Check | Issues | Domains |")
        add("|---|---|---|---:|---|")
        for row in summary.itertuples():
            add(
                f"| `{row.rule_id}` | {row.severity} | {row.description} | "
                f"{row.issues:,} | {row.domains} |"
            )
        add("")
    add("Full detail, one row per finding, is in `reports/validation_issues.csv`.")
    add("")

    add("## Rules implemented")
    add("")
    add("| Rule | Check |")
    add("|---|---|")
    for rule_id, (_, description) in ALL_RULES.items():
        add(f"| `{rule_id}` | {description} |")
    add("")

    add("## Controlled terminology bindings")
    add("")
    add("| Variable | CDISC codelist |")
    add("|---|---|")
    for variable, codelist in sorted(CODELIST_BINDINGS.items()):
        add(f"| `{variable}` | {codelist} |")
    add("")
    add("### Deliberately unbound")
    add("")
    add(
        "A variable with no usable published codelist is left unchecked rather than "
        "checked against an approximation, so the gap stays visible."
    )
    add("")
    add("| Variable | Why |")
    add("|---|---|")
    for variable, reason in sorted(UNBOUND_VARIABLES.items()):
        add(f"| `{variable}` | {reason} |")
    add("")
    return "\n".join(lines) + "\n"


def write(issues: list[Issue], docs_dir: Path, reports_dir: Path) -> pd.DataFrame:
    frame = to_frame(issues)
    reports_dir.mkdir(parents=True, exist_ok=True)
    frame.to_csv(reports_dir / "validation_issues.csv", index=False)

    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "validation_rules.md").write_text(render_rules_markdown(issues))
    return frame
