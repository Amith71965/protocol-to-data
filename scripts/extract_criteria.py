"""Extract eligibility criteria from the protocol and score the result.

Reads the criteria prose from the Clinical Study Report, sends it to the
configured model, validates the response against the Pydantic schema, and
scores it against the hand-labelled gold set.

Responses are cached by a hash of the request, so a second run costs nothing
and the test suite never makes a network call. With no API key configured the
run is cache-only: it succeeds if a cached response exists and otherwise says
plainly that none does.

Usage:
    uv run python scripts/extract_criteria.py [--live]
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import warnings
from datetime import date

from p2d.criteria.align import align, load_gold
from p2d.criteria.cache import CacheMissError, ResponseCache
from p2d.criteria.extract import ExtractionError, extract
from p2d.criteria.protocol import load_criteria_text
from p2d.criteria.provider import MissingCredentialsError, build_provider
from p2d.paths import CACHE_DIR, DATA_DIR, GOLD_DIR, RAW_DIR, REPORTS_DIR, ensure_dirs
from p2d.settings import load_settings


def render_metrics(report, settings, n_criteria: int) -> str:
    lines: list[str] = []
    add = lines.append
    add("# Criteria extraction metrics")
    add("")
    add(f"Generated by `scripts/extract_criteria.py` on {date.today().isoformat()}.")
    add(f"Provider `{settings.llm_provider}`, model `{settings.llm_model}`.")
    add("")
    add(
        "The protocol's eligibility prose is read from the Clinical Study Report and "
        "extracted into a Pydantic schema. The result is scored against a gold set of "
        f"{n_criteria} criteria hand-labelled from the study's own TI domain."
    )
    add("")

    scores = report.extraction
    add("## Extraction")
    add("")
    add("Did the model find each published criterion, and nothing that is not one?")
    add("")
    add("| Metric | Value |")
    add("|---|---:|")
    add(f"| Precision | {scores.precision:.1%} |")
    add(f"| Recall | {scores.recall:.1%} |")
    add(f"| F1 | {scores.f1:.3f} |")
    add(f"| Found | {scores.true_positives} of {n_criteria} |")
    add("")
    if report.missed:
        add(f"Missed: {', '.join(f'`{c}`' for c in report.missed)}")
        add("")
    if report.spurious:
        add(f"Not in the published set: {', '.join(f'`{c}`' for c in report.spurious)}")
        add("")

    add("## Testability labelling")
    add("")
    add(
        "Of the criteria it found, did it judge correctly what the data can answer? "
        "The confusion matrix is shown because overall accuracy alone would flatter a "
        "model that labelled everything partially testable."
    )
    add("")
    add(
        f"**Accuracy {report.testability_accuracy:.1%}** "
        f"({report.testability_correct} of {report.testability_total})"
    )
    add("")
    matrix = report.confusion
    add("| gold \\ predicted | " + " | ".join(matrix.columns) + " |")
    add("|---" * (len(matrix.columns) + 1) + "|")
    for label in matrix.index:
        add(
            f"| **{label}** | "
            + " | ".join(str(matrix.loc[label, c]) for c in matrix.columns)
            + " |"
        )
    add("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--live", action="store_true", help="allow a real API call on a cache miss")
    args = parser.parse_args(argv)

    logging.getLogger("pypdf").setLevel(logging.ERROR)
    warnings.filterwarnings("ignore")
    ensure_dirs()

    csr = RAW_DIR / "docs" / "cdiscpilot01.pdf"
    gold_path = GOLD_DIR / "criteria_gold.csv"
    if not csr.exists():
        print("No study report. Run scripts/download_data.py first.", file=sys.stderr)
        return 1
    if not gold_path.exists():
        print("No gold set. Run scripts/build_gold_set.py first.", file=sys.stderr)
        return 1

    settings = load_settings()
    if args.live:
        settings = settings.model_copy(update={"llm_cache_only": False})

    criteria_text = load_criteria_text(csr)
    print(f"Protocol criteria text: {len(criteria_text):,} characters")

    cache = ResponseCache(CACHE_DIR)
    try:
        provider = build_provider(settings, cache)
        extraction = extract(provider, criteria_text.combined)
    except CacheMissError as exc:
        print(f"\nNo cached extraction, and no live call was requested.\n  {exc}", file=sys.stderr)
        print(
            "\nTo run it for real: put an API key in .env and re-run with --live.",
            file=sys.stderr,
        )
        return 2
    except MissingCredentialsError as exc:
        print(f"\n{exc}", file=sys.stderr)
        return 2
    except ExtractionError as exc:
        print(f"\nExtraction failed: {exc}", file=sys.stderr)
        return 1

    output = DATA_DIR / "criteria_extracted.json"
    output.write_text(json.dumps(extraction.model_dump(mode="json"), indent=2))

    gold = load_gold(gold_path)
    report = align(extraction.criteria, gold)

    print(f"\nExtracted {len(extraction.criteria)} criteria")
    print(
        f"  extraction  precision {report.extraction.precision:.1%}  "
        f"recall {report.extraction.recall:.1%}  F1 {report.extraction.f1:.3f}"
    )
    print(
        f"  testability accuracy  {report.testability_accuracy:.1%} "
        f"({report.testability_correct}/{report.testability_total})"
    )
    if report.missed:
        print(f"  missed: {', '.join(report.missed)}")

    metrics_path = REPORTS_DIR / "extraction_metrics.md"
    metrics_path.write_text(render_metrics(report, settings, len(gold)))
    print(f"\n  {output}\n  {metrics_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
