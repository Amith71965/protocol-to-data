"""Run the eligibility rules against the mapped data and report deviations.

Writes:
  reports/deviations.csv      every flagged subject, with the record behind it
  reports/evaluations.csv     every outcome, including pass and not evaluable
  reports/coverage.md         how much of the protocol is actually checked

Usage:
    uv run python scripts/check_deviations.py
"""

from __future__ import annotations

import sys
from datetime import date

from p2d.criteria.align import load_gold
from p2d.deviations.engine import (
    build_context,
    coverage,
    deviations_with_subject_detail,
    evaluate,
    load_domains,
    per_criterion_summary,
)
from p2d.deviations.outcomes import to_frame
from p2d.deviations.rules import EXECUTABLE_RULES
from p2d.paths import GOLD_DIR, REPORTS_DIR, SDTM_DIR, ensure_dirs


def render_coverage(cov, summary, gold) -> str:
    lines: list[str] = []
    add = lines.append
    add("# Criteria coverage")
    add("")
    add(f"Generated by `scripts/check_deviations.py` on {date.today().isoformat()}.")
    add("")
    add(
        f"The protocol states **{cov.total_criteria} eligibility criteria**. "
        f"**{cov.executable}** have an executable rule here. That is "
        f"**{cov.rule_coverage:.0%} coverage**, and the remaining "
        f"{cov.no_rule} are listed below with the reason."
    )
    add("")
    add(
        "Coverage is reported this way deliberately. A rule that evaluates part of a "
        "criterion and reports a clean pass would overstate what was checked, so a "
        "criterion either gets a rule whose limits are stated, or no rule at all."
    )
    add("")

    add("## Outcomes")
    add("")
    add(f"Rules were evaluated against the **{cov.subjects} randomized subjects**.")
    add("Screen failures are excluded: the study excluded them correctly, so flagging")
    add("one would be a false positive.")
    add("")
    add("| Outcome | Evaluations |")
    add("|---|---:|")
    for outcome, count in cov.outcomes.items():
        add(f"| {outcome} | {count:,} |")
    add("")

    add("## Per criterion")
    add("")
    add("| Criterion | Category | Gold testability | Rule | Pass | Deviation | Not evaluable |")
    add("|---|---|---|---|---:|---:|---:|")
    # "pass" is a keyword, so itertuples would rename the column positionally.
    for _, row in summary.iterrows():
        mark = "yes" if row["has_executable_rule"] else "—"
        add(
            f"| `{row['criterion_id']}` | {row['category'].title()} | {row['gold_testability']} | "
            f"{mark} | {row['pass']} | {row['deviation']} | {row['not_evaluable']} |"
        )
    add("")

    without = summary[~summary["has_executable_rule"]]
    add("## Why the other criteria have no rule")
    add("")
    add("| Criterion | Reason |")
    add("|---|---|")
    for row in without.itertuples():
        reason = row.reason_no_rule or "No data in the published study speaks to this criterion."
        add(f"| `{row.criterion_id}` | {reason} |")
    add("")
    return "\n".join(lines) + "\n"


def main() -> int:
    ensure_dirs()
    if not any(SDTM_DIR.glob("*.parquet")):
        print("No mapped SDTM. Run scripts/build_sdtm.py first.", file=sys.stderr)
        return 1

    domains = load_domains(SDTM_DIR)
    missing = {"DM", "QS", "LB"} - set(domains)
    if missing:
        print(f"Missing mapped domains: {sorted(missing)}", file=sys.stderr)
        return 1

    gold = load_gold(GOLD_DIR / "criteria_gold.csv")
    context = build_context(domains["DM"], domains["QS"], domains["LB"])
    evaluations = evaluate(context)

    to_frame(evaluations).to_csv(REPORTS_DIR / "evaluations.csv", index=False)
    flagged = deviations_with_subject_detail(evaluations, context)
    flagged.to_csv(REPORTS_DIR / "deviations.csv", index=False)

    cov = coverage(evaluations, gold, context)
    summary = per_criterion_summary(evaluations, gold)
    (REPORTS_DIR / "coverage.md").write_text(render_coverage(cov, summary, gold))

    print(
        f"{len(EXECUTABLE_RULES)} of {cov.total_criteria} criteria have an executable rule "
        f"({cov.rule_coverage:.0%} coverage)"
    )
    print(f"Evaluated {cov.subjects} randomized subjects")
    for outcome, count in cov.outcomes.items():
        print(f"  {outcome:15s} {count:,}")
    print(f"\n{len(flagged)} deviations flagged")
    if len(flagged):
        print(
            flagged[["usubjid", "criterion_id", "observed", "SITEID", "ARM"]]
            .head(12)
            .to_string(index=False)
        )
    print(f"\n  {REPORTS_DIR / 'coverage.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
